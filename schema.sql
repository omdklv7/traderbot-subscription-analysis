-- 1. Зарегистрированные пользователи TraderBot.
CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registered_at TIMESTAMPTZ NOT NULL,
    initial_model VARCHAR(20) NOT NULL,
    signup_source VARCHAR(50),
    auth_method VARCHAR(20) NOT NULL
);
ALTER TABLE users
ADD CONSTRAINT chk_users_initial_model
CHECK (initial_model IN ('subscription', 'license'));
ALTER TABLE users
ADD CONSTRAINT chk_users_auth_method
CHECK (auth_method IN ('email', 'telegram'));


-- 2. Подписки пользователей.
CREATE TABLE subscriptions (
	subscription_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
	user_id bigint NOT NULL UNIQUE REFERENCES users(user_id),
	created_at timestamptz NOT NULL
);


-- 3. История попыток оплаты подписки.
CREATE TABLE payments (
	payment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	subscription_id bigint NOT NULL REFERENCES subscriptions(subscription_id),
	initiated_at timestamptz NOT NULL,
	confirmed_at timestamptz,
	amount_usd NUMERIC(10, 2) NOT NULL,
	METHOD varchar(20) NOT NULL,
	status varchar(20) NOT NULL,
	CONSTRAINT chk_payments_amount
    CHECK (amount_usd > 0),
	CONSTRAINT chk_payments_method
    CHECK (METHOD IN ('sbp', 'crypto')),	
	CONSTRAINT chk_payments_status
    CHECK (status IN ('pending', 'confirmed', 'failed')),
	CONSTRAINT chk_payments_confirmation
    CHECK (
        (status = 'confirmed'
AND confirmed_at IS NOT NULL
AND confirmed_at >= initiated_at)
OR
        (status IN ('pending', 'failed')
AND confirmed_at IS NULL)
    )
);
ALTER TABLE payments
ADD CONSTRAINT uq_payments_payment_subscription
UNIQUE (payment_id, subscription_id);


-- 4. Оплаченные периоды действия подписок.
CREATE TABLE subscription_periods (
	period_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	subscription_id bigint NOT NULL REFERENCES subscriptions(subscription_id),
	payment_id bigint NOT NULL UNIQUE REFERENCES payments(payment_id),
	period_no integer NOT NULL CHECK (period_no > 0),
	starts_at timestamptz NOT NULL, 
	ends_at timestamptz NOT NULL,
	canceled_at timestamptz,
	CONSTRAINT uq_subscription_periods_period_no
UNIQUE (subscription_id, period_no),
	CONSTRAINT chk_ends_at
	CHECK (ends_at > starts_at),
	CONSTRAINT chk_canceled_at
	CHECK (canceled_at >= starts_at
AND canceled_at < ends_at)
);
ALTER TABLE subscription_periods
ADD CONSTRAINT fk_periods_payment_subscription
FOREIGN KEY (payment_id, subscription_id)
REFERENCES payments(payment_id, subscription_id);


-- 5. Первичная активация торговой системы после оплаты.
CREATE TABLE activations (
	activation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	subscription_id bigint NOT NULL UNIQUE REFERENCES subscriptions(subscription_id),
	requested_at timestamptz NOT NULL,
	completed_at timestamptz,
	status varchar(20) NOT NULL CHECK (status IN ('pending', 'completed', 'failed')),
	CONSTRAINT chk_completed_at
	CHECK (completed_at >= requested_at),
	CONSTRAINT chk_status CHECK ((status = 'completed'
AND completed_at IS NOT NULL)
OR (status IN ('pending', 'failed')
AND completed_at IS NULL))  
);


-- 6. История настроек торговой системы.
CREATE TABLE setting_changes (
    change_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT NOT NULL REFERENCES subscriptions(subscription_id),
    changed_at TIMESTAMPTZ NOT NULL,
    risk_level VARCHAR(20) NOT NULL
        CHECK (risk_level IN ('low', 'medium', 'high')),
    trading_mode VARCHAR(20) NOT NULL
        CHECK (trading_mode IN ('conservative', 'balanced', 'aggressive'))
);


-- 7. Технические инциденты TraderBot.
CREATE TABLE incidents (
    incident_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TIMESTAMPTZ NOT NULL,
    resolved_at TIMESTAMPTZ,
    severity VARCHAR(20) NOT NULL
        CHECK (severity IN ('low', 'medium', 'high', 'critical')),
    category VARCHAR(50) NOT NULL,

    CONSTRAINT chk_incidents_dates
        CHECK (resolved_at IS NULL
OR resolved_at >= started_at)
);


-- 8. Воздействие технических инцидентов на подписчиков.
CREATE TABLE incident_impacts (
    impact_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents(incident_id),
    subscription_id BIGINT NOT NULL REFERENCES subscriptions(subscription_id),
    affected_at TIMESTAMPTZ NOT NULL,
    restored_at TIMESTAMPTZ,

    CONSTRAINT uq_incident_subscription
        UNIQUE (incident_id, subscription_id),

    CONSTRAINT chk_incident_impacts_dates
        CHECK (restored_at IS NULL
OR restored_at >= affected_at)
);


-- 9. История обращений пользователей в техническую поддержку.
CREATE TABLE support_tickets (
    ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT NOT NULL REFERENCES subscriptions(subscription_id),
    opened_at TIMESTAMPTZ NOT NULL,
    closed_at TIMESTAMPTZ,
    category VARCHAR(30) NOT NULL
        CHECK (category IN ('activation', 'payment', 'technical', 'general')),

    CONSTRAINT chk_support_tickets_dates
        CHECK (closed_at IS NULL
OR closed_at >= opened_at)
);


-- 10. Покупки бессрочных лицензий TraderBot.
CREATE TABLE license_purchases (
    license_purchase_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    purchased_at TIMESTAMPTZ NOT NULL,
    amount_usd NUMERIC(10, 2) NOT NULL
        CHECK (amount_usd > 0)
);





